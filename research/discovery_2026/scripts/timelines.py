"""Observation timelines (mission section 7.4) for every target with photometry.

    PYTHONPATH=.:research:research/discovery_2026/scripts .venv/bin/python research/discovery_2026/scripts/timelines.py

For each target: every D3-D6 exposure (time, detector, channel wavelength, release, photometry status), grouped into
visits and passes with the same rules as ice_fit.py, the time needed to sweep the H2O and CO2 band windows in each
visit, and whether each epoch is complete for each band.

Output: OBSERVATION_TIMELINES/NAME.csv (exposures), NAME.png (wavelength vs time), and index.csv / INDEX.md
(one row per target, visit and band).
"""
import csv
import json
from pathlib import Path

import numpy as np

import ice_fit as I

OUT = I.ROOT / "OBSERVATION_TIMELINES"
SAMPLE = I.ROOT / "data" / "lists" / "sample.csv"


def exposures(name):
    rows = list(csv.DictReader(open(I.PHOT / f"{name}.csv")))
    out = []
    for r in rows:
        out.append({"mjd": float(r["mjd"]), "det": int(r["det"]), "wl_um": float(r["wl_um"]),
                    "bw_um": float(r["bw_um"]), "collection": r["collection"], "status": r["status"],
                    "n_core_good": int(r["n_core_good"]) if r["n_core_good"] else 0,
                    "snr": float(r["flux_jy"]) / float(r["err_jy"]) if r["status"] == "ok" and float(r["err_jy"]) > 0
                    else float("nan")})
    out.sort(key=lambda r: r["mjd"])
    return out


def sweep(pts, lo, hi):
    t = [p["mjd"] for p in pts if lo <= p["wl_um"] <= hi]
    return (max(t) - min(t)) if len(t) >= 2 else None


def plot(name, ex, res, path):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    fig, ax = plt.subplots(figsize=(9, 3.6))
    for det, m in zip((3, 4, 5, 6), "o^sD"):
        q = [p for p in ex if p["det"] == det]
        used = [p for p in q if p["status"] == "ok" and p["n_core_good"] >= I.MIN_CORE_GOOD]
        bad = [p for p in q if p not in used]
        ax.scatter([p["mjd"] for p in used], [p["wl_um"] for p in used], s=10, marker=m, label=f"D{det}")
        if bad:
            ax.scatter([p["mjd"] for p in bad], [p["wl_um"] for p in bad], s=14, marker="x", color="0.5")
    for b, c in (("H2O", "C0"), ("CO2", "C3")):
        lo, hi = I.BANDS[b]["fit"]
        ax.axhspan(lo, hi, color=c, alpha=0.06)
        for e in (res.get("bands", {}).get(b, {}).get("epochs") or []):
            ax.axvspan(e["mjd"][0], e["mjd"][1], color=c if e["complete"] else "0.8", alpha=0.08)
    ax.set_xlabel("MJD")
    ax.set_ylabel("channel wavelength (µm)")
    ax.set_title(f"{name}: D3–D6 exposures (x = rejected); shaded = epochs (grey = incomplete)", fontsize=9)
    ax.legend(fontsize=7, ncol=4)
    fig.tight_layout()
    fig.savefig(path, dpi=85)
    plt.close(fig)


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    roles = {r["name"]: r["role"] for r in csv.DictReader(open(SAMPLE))}
    index = []
    for f in sorted(I.PHOT.glob("*.csv")):
        name = f.stem
        ex = exposures(name)
        if not ex:
            continue
        with open(OUT / f"{name}.csv", "w", newline="") as g:
            w = csv.DictWriter(g, fieldnames=list(ex[0]))
            w.writeheader()
            w.writerows(ex)
        jf = I.OUT / f"{name}.json"
        res = json.loads(jf.read_text()) if jf.exists() else {}
        plot(name, ex, res, OUT / f"{name}.png")
        visits = I.clusters([p["mjd"] for p in ex], I.VISIT_GAP)
        for vi, v in enumerate(visits):
            vp = [ex[i] for i in v]
            passes = I.clusters([p["mjd"] for p in vp], I.PASS_GAP)
            row = {"name": name, "role": roles.get(name, "pilot"), "visit": vi,
                   "mjd_start": round(min(p["mjd"] for p in vp), 2), "mjd_end": round(max(p["mjd"] for p in vp), 2),
                   "releases": "+".join(sorted({p["collection"].replace("spherex_", "") for p in vp})),
                   "n_passes": len(passes)}
            for d in (3, 4, 5, 6):
                row[f"n_D{d}"] = sum(p["det"] == d for p in vp)
            for b in ("H2O", "CO2"):
                lo, hi = I.BANDS[b]["fit"]
                s = sweep(vp, lo, hi)
                row[f"{b}_sweep_days"] = round(s, 1) if s is not None else ""
                eps = [e for e in (res.get("bands", {}).get(b, {}).get("epochs") or []) if e["visit"] == vi]
                row[f"{b}_epochs"] = ";".join(f"{e['epoch']}:{'complete' if e['complete'] else 'incomplete'}"
                                              f"{tuple(e['coverage_core_blue_red'])}" for e in eps)
            index.append(row)
    with open(OUT / "index.csv", "w", newline="") as g:
        w = csv.DictWriter(g, fieldnames=list(index[0]))
        w.writeheader()
        w.writerows(index)
    lines = ["# Observation timelines (mission section 7.4)", "",
             "One row per target and SPHEREx visit. Generated by `scripts/timelines.py` from the per-exposure photometry.",
             "Per-target exposure lists: `NAME.csv`; figures: `NAME.png` (wavelength vs time; shaded = epochs).",
             "Epoch label `v.k` = pass k of visit v (a pass is its own epoch only if every pass of the visit is complete).",
             "Coverage tuple = number of usable exposures in (core, blue, red) windows of the band.", "",
             "| " + " | ".join(index[0]) + " |", "|" + "---|" * len(index[0])]
    lines += ["| " + " | ".join(str(r[k]) for k in index[0]) + " |" for r in index]
    (OUT / "INDEX.md").write_text("\n".join(lines) + "\n")
    print(len(index), "visit rows for", len({r['name'] for r in index}), "targets")


if __name__ == "__main__":
    main()
