"""Day 1 check: for each official target, find SPHEREx coverage and open one real cutout.

Run from the repo root:  python -m scripts.day1_report
Writes notes/DAY1_REPORT.md and cache/day1_report.json.
"""
import json
import time

from backend.app import archive
from backend.app.config import CACHE_DIR, REPO_ROOT
from backend.app.coords import parse_coordinates
from backend.app.motion import position_at, separation_arcsec
from backend.app.resolve import ResolverUnavailable, resolve_name
from backend.app.targets import OFFICIAL_TARGETS

QUERY_YEAR = 2026.0  # middle of the SPHEREx data so far (Apr 2025 - Oct 2026)


def check_target(target: dict) -> dict:
    result = {"label": target["label"], "kind": target["kind"]}
    try:
        star = resolve_name(target["simbad"])
        result["position_source"] = f"SIMBAD ({star['server']}): {star['simbad_id']}"
    except (LookupError, ResolverUnavailable) as exc:
        if "challenge_position" not in target:
            result["error"] = str(exc)
            return result
        ra, dec = parse_coordinates(target["challenge_position"])
        star = {"ra": ra, "dec": dec, "pmra": None, "pmdec": None, "epoch": 2000.0}
        result["position_source"] = f"challenge text (SIMBAD failed: {exc})"

    pmra, pmdec = star["pmra"] or 0.0, star["pmdec"] or 0.0
    result["pm_known"] = star["pmra"] is not None
    ra, dec = position_at(star["ra"], star["dec"], pmra, pmdec, star["epoch"], QUERY_YEAR)
    result.update(
        ra_j2000=round(star["ra"], 6), dec_j2000=round(star["dec"], 6),
        pmra=pmra, pmdec=pmdec,
        ra_query=round(ra, 6), dec_query=round(dec, 6),
        moved_since_2000_arcsec=round(separation_arcsec(star["ra"], star["dec"], ra, dec), 1),
    )

    t0 = time.time()
    images = archive.find_images(ra, dec)
    result["query_seconds"] = round(time.time() - t0, 1)
    result["coverage"] = archive.summarize(images)
    if not images:
        return result

    # One sample cutout per data release, so the two releases' headers can be compared.
    preferred = 6 if target["kind"] == "cold" else 2
    result["samples"] = []
    for release in ("qr2", "qr3"):
        in_release = [im for im in images if im.collection.startswith(f"spherex_{release}")]
        if not in_release:
            continue
        sample = next((im for im in in_release if im.detector == preferred), in_release[0])
        archive.attach_paths([sample])
        t0 = time.time()
        path = archive.download_cutout(sample, ra, dec, size_deg=0.05)
        result["samples"].append({
            "release": release,
            "image": archive.image_to_dict(sample),
            "seconds": round(time.time() - t0, 1),
            "mb": round(path.stat().st_size / 1e6, 2),
            "cutout": archive.describe_cutout(path),
        })
    return result


def to_markdown(results: list[dict]) -> str:
    lines = [
        "# Day 1 report: SPHEREx coverage of the 5 official targets",
        "",
        f"Generated by `python -m scripts.day1_report` on {time.strftime('%Y-%m-%d %H:%M')}. "
        f"Positions moved with proper motion to {QUERY_YEAR} before searching.",
        "",
        "| Target | Images | Exposures | First | Last | Epochs | D1 | D2 | D3 | D4 | D5 | D6 | Collections | Latest release |",
        "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    for r in results:
        c = r.get("coverage", {})
        if not c.get("n_images"):
            lines.append(f"| {r['label']} | 0 | | | | | | | | | | | | {r.get('error', '')} |")
            continue
        d = c["per_detector"]
        cols = ", ".join(f"{k.removeprefix('spherex_')} {n}" for k, n in c["per_collection"].items())
        lines.append(
            f"| {r['label']} | {c['n_images']} | {c['n_exposures']} | {c['first']} | {c['last']} | "
            f"{c['n_epochs']} | " + " | ".join(str(d[k]) for k in range(1, 7))
            + f" | {cols} | {c['latest_release'][:10]} |"
        )
    lines += ["", "## Epochs per target", ""]
    for r in results:
        c = r.get("coverage", {})
        lines.append(f"### {r['label']}")
        lines.append(f"- Position: {r.get('position_source', '?')}; moved {r.get('moved_since_2000_arcsec', '?')}″ since 2000.")
        for ep in c.get("epochs", []):
            lines.append(f"- Epoch {ep['id']}: {ep['date']} ({ep['n_images']} images, MJD {ep['mjd_min']:.1f}–{ep['mjd_max']:.1f})")
        for s in r.get("samples", []):
            cut = s["cutout"]
            lines.append(
                f"- Sample cutout {s['release'].upper()} D{s['image']['detector']}: {s['mb']} MB, "
                f"{s['seconds']} s, MJD-AVG {cut['MJD-AVG']}, {cut['pct_bad']}% bad pixels, "
                f"{cut['pct_source']}% SOURCE-labelled, extensions "
                + ", ".join(f"{n}{list(sh)}" for n, sh in cut["extensions"])
            )
        lines.append("")
    lines += ["## Flag bits per release (from the FLAGS header)", ""]
    seen = set()
    for r in results:
        for s in r.get("samples", []):
            if s["release"] in seen:
                continue
            seen.add(s["release"])
            bits = s["cutout"]["flag_bits"]
            lines.append(f"- **{s['release'].upper()}**: " + ", ".join(f"{k}={v}" for k, v in bits.items()))
    lines.append("")
    return "\n".join(lines)


def main():
    results = []
    for target in OFFICIAL_TARGETS:
        print(f"... {target['label']}", flush=True)
        try:
            results.append(check_target(target))
        except archive.ArchiveError as exc:
            results.append({"label": target["label"], "error": str(exc)})
        print(json.dumps({k: v for k, v in results[-1].items() if k not in ("coverage", "samples")}, default=str))
    CACHE_DIR.mkdir(exist_ok=True)
    (CACHE_DIR / "day1_report.json").write_text(json.dumps(results, indent=1, default=str))
    (REPO_ROOT / "notes" / "DAY1_REPORT.md").write_text(to_markdown(results))
    print("wrote notes/DAY1_REPORT.md")


if __name__ == "__main__":
    main()
